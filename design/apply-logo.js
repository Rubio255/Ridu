// Usage: node design/apply-logo.js <namai|sirdis|kelias>
const fs = require("fs"), path = require("path");
const L = require("./logos.js"), key = process.argv[2];
if (!L[key]) throw new Error("unknown logo " + key);
const root = path.join(__dirname, "..");
const svg = L[key]();
// Demo apps: replace the header mark (any previous content)
for (const f of ["vezimas-demo.html", "vezimas-klientams.html", "vezimas-admin.html"]) {
  const p = path.join(root, "demo", f);
  let s = fs.readFileSync(p, "utf8");
  s = s.replace(/<div class="mark"[^>]*>[\s\S]*?<\/div><div><h1>/, `<div class="mark" aria-hidden="true">${svg}</div><div><h1>`);
  s = s.replace(/\.logo \.mark\{[^}]*\}/, ".logo .mark{width:34px;height:34px;flex:none}.logo .mark svg{width:100%;height:100%;display:block}");
  fs.writeFileSync(p, s);
}
// Real app: SVG favicon + logo component
fs.writeFileSync(path.join(root, "public/icon.svg"), svg);
fs.writeFileSync(path.join(root, "src/components/logo.tsx"),
  `// Generated by design/apply-logo.js (${key})\nexport function Logo({ size = 34 }: { size?: number }) {\n  return <span aria-hidden="true" style={{ width: size, height: size, display: "inline-block", flex: "none" }} dangerouslySetInnerHTML={{ __html: ${JSON.stringify(svg.replace("<svg ", '<svg width="100%" height="100%" '))} }} />;\n}\n`);
// PWA PNG icons: full-bleed tile so phones can apply their own mask
(async () => {
  const { chromium } = require("playwright");
  const b = await chromium.launch();
  for (const n of [192, 512]) {
    const p = await b.newPage({ viewport: { width: n, height: n } });
    await p.setContent(`<style>html,body{margin:0}svg{width:${n}px;height:${n}px;display:block}</style>${svg.replace('rx="14"', 'rx="0"')}`);
    await p.screenshot({ path: path.join(root, `public/icon-${n}.png`), omitBackground: true });
  }
  await b.close();
})();
